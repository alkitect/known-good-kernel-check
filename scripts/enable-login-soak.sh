#!/usr/bin/env bash
# Install + enable user systemd unit for background login soak (PBIT).
# Idempotent. Does not require sudo.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
KCG_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"
UNIT_SRC="${KCG_ROOT}/systemd/user/kcg-login-soak.service"
WRAPPER="${HOME}/.local/bin/kcg-login-soak"
UNIT_DST="${HOME}/.config/systemd/user/kcg-login-soak.service"
TRACKING="${KCG_CAMPAIGN_TRACKING:-${KCG_ROOT}/docs/campaign-tracking.example.md}"

usage() {
  cat <<EOF
Usage: $(basename "$0") [--disable]

  Installs ~/.local/bin/kcg-login-soak wrapper + user unit, enables on
  graphical-session.target (runs once per login/boot after ~45s delay).

  --disable   stop/disable unit + set TRACKING login_soak_enabled: no

Env: KCG_CAMPAIGN_TRACKING — override lane tracking; wrapper uses lane resolver
EOF
}

set_tracking_enabled() {
  local val="$1"
  [[ -f "${TRACKING}" ]] || return 0
  if grep -q 'login_soak_enabled:' "${TRACKING}"; then
    sed -i "s/login_soak_enabled: .*/login_soak_enabled: ${val}/" "${TRACKING}" || true
  fi
  if [[ "${val}" == "yes" ]]; then
    local today
    today="$(date -u +%Y-%m-%d)"
    if grep -q 'login_soak_enabled_at:' "${TRACKING}"; then
      sed -i "s/login_soak_enabled_at: .*/login_soak_enabled_at: \"${today}\"/" "${TRACKING}" || true
    fi
  fi
}

DISABLE=0
while [[ $# -gt 0 ]]; do
  case "$1" in
    --disable) DISABLE=1; shift ;;
    -h|--help) usage; exit 0 ;;
    *) echo "Unknown: $1" >&2; usage; exit 2 ;;
  esac
done

if [[ "${DISABLE}" -eq 1 ]]; then
  systemctl --user disable --now kcg-login-soak.service 2>/dev/null || true
  set_tracking_enabled no
  echo "Disabled kcg-login-soak.service + TRACKING login_soak_enabled: no"
  echo "Wrapper kept at ${WRAPPER}"
  exit 0
fi

[[ -f "${UNIT_SRC}" ]] || { echo "ERROR: missing ${UNIT_SRC}" >&2; exit 2; }
[[ -f "${KCG_ROOT}/scripts/run-login-soak.sh" ]] || { echo "ERROR: missing run-login-soak.sh" >&2; exit 2; }

mkdir -p "${HOME}/.local/bin" "${HOME}/.config/systemd/user"

# Resolve TRACKING to active lane when present
# shellcheck source=lib/kcg-lane.sh
source "${KCG_ROOT}/scripts/lib/kcg-common.sh" 2>/dev/null || true
# shellcheck source=lib/kcg-lane.sh
source "${KCG_ROOT}/scripts/lib/kcg-lane.sh"
kcg_lane_apply_if_needed 2>/dev/null || true
TRACKING="${KCG_CAMPAIGN_TRACKING:-${TRACKING}}"

cat >"${WRAPPER}" <<EOF
#!/usr/bin/env bash
# Generated by enable-login-soak.sh — do not edit; re-run enable to refresh.
set -euo pipefail
export KCG_ROOT="${KCG_ROOT}"
export KCG_EVIDENCE="\${KCG_EVIDENCE:-${KCG_ROOT}/evidence}"
export KCG_PROGRESS="\${KCG_PROGRESS:-plain}"
# Lane resolver picks campaigns/\$(uname -r)/ — do not bake a fixed profile
export DISPLAY="\${DISPLAY:-:0}"
export WAYLAND_DISPLAY="\${WAYLAND_DISPLAY:-wayland-0}"
export XDG_RUNTIME_DIR="\${XDG_RUNTIME_DIR:-/run/user/\$(id -u)}"
exec "${KCG_ROOT}/scripts/run-login-soak.sh" "\$@"
EOF
chmod +x "${WRAPPER}"

install -m 644 "${UNIT_SRC}" "${UNIT_DST}"

# Import live session display into user manager when available (helps PassEnvironment later)
systemctl --user import-environment DISPLAY WAYLAND_DISPLAY XDG_RUNTIME_DIR 2>/dev/null || true

systemctl --user daemon-reload
systemctl --user enable kcg-login-soak.service
set_tracking_enabled yes

echo "Enabled kcg-login-soak.service (WantedBy=graphical-session.target)"
echo "  wrapper: ${WRAPPER}"
echo "  unit:    ${UNIT_DST}"
echo "  topic:   ${KCG_ROOT}"
echo "Starts ~45s after next graphical login; once per session; login-only cap 7 then auto-disable."
echo "Prove now (optional): ${SCRIPT_DIR}/prove-login-soak-now.sh"
echo "Verify: ${SCRIPT_DIR}/verify-login-soak-hook.sh"
echo "Disable: ${SCRIPT_DIR}/enable-login-soak.sh --disable"

systemctl --user is-enabled kcg-login-soak.service
systemctl --user status kcg-login-soak.service --no-pager -l || true
